# Arithmetic operators:
x = 3
y = 3
print(x + y)
print(x - y)   # subtract
print(x * y)   # multiply
print(x / y)   # divide
print(x % y)   # modulus
print(x ** y)  # exponential
# Assignment operators:
# Comparison operators:
print(x == y)
print(x != y)
print(x < y)
print(x > y)
print(x >= y)
print(x <= y)
# Logical operators:
print(x & y) #print both x and y
print(x | y) #any value is printed
# identity operators:
print(x is y)
print(x is not y)
# Membership operators:
text = "my name is sid"
print("name" in text) # gives true or false
# Bitwise operators:
a = 10   # 1010 in binary
b = 4    # 0100 in binary
print("a & b =", a & b)   # 0000 → 0
